  String _term(String value) {
    final names = switch (language) {
      AppLanguage.gujarati => _gujaratiNames,
      AppLanguage.hindi => _hindiNames,
      AppLanguage.english => const <String, String>{},
    };
    if (names.containsKey(value)) return names[value]!;
    final parts = value.split(' ');
    final translated = parts.map((part) => names[part] ?? part).join(' ');
    if (language == AppLanguage.gujarati && value.startsWith('Shukla ')) {
      return 'શુક્લ ${translated.replaceFirst('શુક્લ ', '')}';
    }
    if (language == AppLanguage.gujarati && value.startsWith('Krishna ')) {
      return 'કૃષ્ણ ${translated.replaceFirst('કૃષ્ણ ', '')}';
    }
    if (language == AppLanguage.hindi && value.startsWith('Shukla ')) {
      return 'शुक्ल ${translated.replaceFirst('शुक्ल ', '')}';
    }
    if (language == AppLanguage.hindi && value.startsWith('Krishna ')) {
      return 'कृष्ण ${translated.replaceFirst('कृष्ण ', '')}';
    }
    return translated;
  }

